_CONSTITUTIONAL_RULES_FIXTURE = (
    Path(__file__).resolve().parent.parent / "fixtures" /
    "g6_constitutional_rules.json")


def _load_constitutional_rules() -> ConstitutionalRuleRegistry:
    data = json.loads(_CONSTITUTIONAL_RULES_FIXTURE.read_text(encoding="utf-8"))
    return ConstitutionalRuleRegistry.from_fixture(data)


class ScenarioStimulusError(Exception):
    """A stimulus was structurally invalid (distinct from an expected refusal)."""


@dataclass
class G6Pack:
    scenario_id: str
    scenario_version: str
    threat_class: str
    dir: Path
    decision: Dict[str, Any]                 # decision-grade fixture
    expected_outcome: str                    # SEALED
    hidden_ground_truth: Dict[str, Any]      # SEALED
    expected_phase_trace: List[Dict[str, Any]]  # SEALED
    forbidden_transitions: List[Dict[str, Any]]

    def decision_grade(self) -> Dict[str, Any]:
        """The ONLY projection the decision path may see."""
        return self.decision


def load_g6_pack(path: Path) -> G6Pack:
    scenario = json.loads((path / "scenario.json").read_text(encoding="utf-8"))
    initial = json.loads((path / "initial_epoch.json").read_text(encoding="utf-8"))
    stimuli = [json.loads(line) for line in
               (path / "stimulus_events.jsonl").read_text(encoding="utf-8").splitlines()
               if line.strip()]
    forbidden = json.loads((path / "forbidden_transitions.json").read_text(
        encoding="utf-8"))["forbidden_transitions"]
    evidence_objects: List[Dict[str, Any]] = []
    ev_dir = path / "evidence_objects"
    if ev_dir.is_dir():
        for p in sorted(ev_dir.glob("*.json")):
            evidence_objects.append(json.loads(p.read_text(encoding="utf-8")))
    decision = {
        "scenario_id": scenario["scenario_id"],
        "scenario_version": scenario["scenario_version"],
        "threat_class": scenario["threat_class"],
        "initial_epoch": initial,
        "stimulus_events": stimuli,
        "evidence_objects": evidence_objects,
    }
    expected_trace = json.loads((path / "expected_phase_trace.json").read_text(
        encoding="utf-8"))["phases"]
    return G6Pack(
        scenario_id=scenario["scenario_id"],
        scenario_version=scenario["scenario_version"],
        threat_class=scenario["threat_class"],
        dir=path,
        decision=decision,
        expected_outcome=scenario["expected_outcome"],
        hidden_ground_truth=scenario.get("hidden_ground_truth", {}),
        expected_phase_trace=expected_trace,
        forbidden_transitions=forbidden,
    )


