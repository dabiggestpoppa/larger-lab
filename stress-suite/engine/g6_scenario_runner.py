"""G6 canonical scenario runner (STRESS-G6ER1).

Materializes S20–S24 as canonical scenarios per the Stress Suite Scenario
Catalog execution contract:

    scenario.json            decision-grade fixture + SEALED expectation fields
    initial_epoch.json       starting governance state (contract, authority, seq)
    stimulus_events.jsonl    one JSON stimulus per line, replayed in order
    expected_phase_trace.json SEALED expected phase sequence
    forbidden_transitions.json transitions that must never appear in the trace
    evidence_objects/        evidence records registered in the decision path
    run_receipt.json         generated by this runner (byte-reproducible)
    human_readable_result.md generated by this runner

Sealing law: the DECISION PATH (run_g6_scenario) consumes only the
decision-grade projection — expected_outcome, hidden_ground_truth and
expected_phase_trace are stripped before replay. They are consulted solely by
evaluate_g6_expectation, mirroring the G4/G5 runner split, and the receipt
records expected_outcome_accessed / hidden_ground_truth_accessed = False.

The dispatch is by stimulus EVENT TYPE, never by scenario id: no
`if scenario_id == "S20"` anywhere; every scenario directory drives the same
generic machinery.
"""
