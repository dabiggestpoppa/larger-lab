"""Deterministic local application skeleton (B6-I2, section C1.S3).

The generated app is a fixed file set with no clock, no hostname, no random value and no network
dependency. Two builds of the same name are byte-identical. ``start`` executes the generated
entrypoint in a subprocess, observes its readiness line, sends an orderly stop, enforces a bounded
timeout and requires a zero exit status, so the stage exit gate ("fresh generated app starts
locally") is proven by an executable start rather than by file inspection.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys
import threading

from . import archive
from .refusals import refuse

TEMPLATE = "oce-app-skeleton"
NAME = "app"

APP = {
    "schema": "oce.template.app.v1",
    "name": NAME,
    "version": "v1",
    "python": "3.12",
    "runtime": "subprocess",
    "surfaces": ["api"],
    "cloud": False,
    "telemetry": "local-file",
}

README = """# {name}

A deterministic OCE Book 6 skeleton generated by the B6-I2 template surface.

- Runtime: local subprocess, standard library only.
- Network: none. The app opens no socket and needs no cloud service.
- Compatibility: version `v1`, inherited from the B6-I1 compatibility window.
- Deploy: local only; publication is not authorized by this stage.

Start it locally with `python app/__main__.py` from this directory. The entrypoint prints
`READY {name}`, waits for a `stop` line on standard input, prints `STOPPED` and exits 0.
"""

MIGRATION = """-- 0001_init.sql — deterministic initial schema.
CREATE TABLE IF NOT EXISTS items (
    id TEXT PRIMARY KEY,
    created_at TEXT NOT NULL
);
"""

APP_TEST = '''"""Generated smoke test: the artifact set is complete and offline."""
from __future__ import annotations

import json
import pathlib


def test_app_manifest_is_offline() -> None:
    app = json.loads(pathlib.Path("app.json").read_text(encoding="utf-8"))
    assert app["cloud"] is False
    assert app["version"] == "v1"
'''

APP_INIT = '''"""Generated application package."""
'''

APP_MAIN = '''"""Generated local entrypoint: initialize, report readiness, wait, stop, exit 0."""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main() -> int:
    app = json.loads((ROOT / "app.json").read_text(encoding="utf-8"))
    deploy = json.loads((ROOT / "deploy.json").read_text(encoding="utf-8"))
    if app.get("cloud") is not False or deploy.get("requires_cloud") is not False:
        print("REFUSED_CLOUD", flush=True)
        return 2
    if app.get("version") != "v1":
        print("REFUSED_UNKNOWN_VERSION", flush=True)
        return 2
    print("READY " + app["name"], flush=True)
    for line in sys.stdin:
        if line.strip() == "stop":
            break
    print("STOPPED", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

TELEMETRY = {
    "schema": "oce.template.telemetry.v1",
    "sink": "local-file",
    "network": False,
    "fields": ["event", "status"],
}

DEPLOY = {
    "schema": "oce.template.deploy.v1",
    "target": "local",
    "requires_cloud": False,
    "publication": "NOT_AUTHORIZED",
}

FILES = (
    "README.md",
    "app.json",
    "app/__init__.py",
    "app/__main__.py",
    "deploy.json",
    "migrations/0001_init.sql",
    "telemetry.json",
    "tests/test_app.py",
)

START_TIMEOUT = 15.0


def _text(obj) -> str:
    return json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def build(name: str = NAME) -> dict:
    """Return the frozen file set: path -> exact text. Deterministic for a given name."""
    if not isinstance(name, str) or not name or "/" in name or "\\" in name:
        refuse("REFUSED_INVALID_MANIFEST", name)
    app = dict(APP, name=name)
    return {
        "README.md": README.format(name=name),
        "app.json": _text(app),
        "app/__init__.py": APP_INIT,
        "app/__main__.py": APP_MAIN,
        "deploy.json": _text(DEPLOY),
        "migrations/0001_init.sql": MIGRATION,
        "telemetry.json": _text(TELEMETRY),
        "tests/test_app.py": APP_TEST,
    }


def manifest(name: str = NAME) -> dict:
    files = build(name)
    entries = [{"path": path, "content": files[path], "mode": "file"}
               for path in sorted(files)]
    return {
        "schema": archive.SCHEMA,
        "template": TEMPLATE,
        "version": archive.VERSION,
        "payload_digest": archive.payload_digest(entries),
        "entries": entries,
    }


def write(dest, name: str = NAME) -> dict:
    """Install the skeleton into an absent or empty directory."""
    return archive.install(manifest(name), dest)


def _read_until(stream, marker: str, timeout: float) -> bool:
    seen = threading.Event()

    def reader() -> None:
        for line in stream:
            if line.strip() == marker:
                seen.set()
                return

    threading.Thread(target=reader, daemon=True).start()
    return seen.wait(timeout)


def start(dest, timeout: float = START_TIMEOUT) -> dict:
    """Execute the generated app locally and require readiness, shutdown and exit 0."""
    root = pathlib.Path(dest)
    expected = build(NAME)
    missing = [path for path in FILES if not (root / path).is_file()]
    if missing:
        refuse("REFUSED_INVALID_MANIFEST", f"missing artifacts: {missing}")
    app = json.loads((root / "app.json").read_text(encoding="utf-8"))
    deploy = json.loads((root / "deploy.json").read_text(encoding="utf-8"))
    telemetry = json.loads((root / "telemetry.json").read_text(encoding="utf-8"))
    if app.get("cloud") is not False or deploy.get("requires_cloud") is not False:
        refuse("REFUSED_CLOUD", "app declares a cloud requirement")
    if telemetry.get("network") is not False:
        refuse("REFUSED_NETWORK", "telemetry declares a network sink")
    if deploy.get("publication") != "NOT_AUTHORIZED":
        refuse("REFUSED_INVALID_MANIFEST", "generated app claims publication authority")
    for path in FILES:
        if (root / path).read_text(encoding="utf-8") != expected[path]:
            refuse("REFUSED_INVALID_MANIFEST", f"artifact differs from the build: {path}")
    env = dict(os.environ, PYTHONHASHSEED="0", PYTHONDONTWRITEBYTECODE="1",
               PYTHONNOUSERSITE="1")
    env.pop("PYTHONPATH", None)
    proc = subprocess.Popen([sys.executable, "-E", "-s", "app/__main__.py"], cwd=str(root),
                            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, env=env)
    try:
        ready = _read_until(proc.stdout, f"READY {app['name']}", timeout)
        if not ready:
            proc.kill()
            proc.wait(timeout=timeout)
            refuse("REFUSED_START_TIMEOUT", f"no readiness within {timeout}s")
        assert proc.stdin is not None
        proc.stdin.write("stop\n")
        proc.stdin.flush()
        code = proc.wait(timeout=timeout)
        rest = proc.stdout.read()
        if code != 0:
            refuse("REFUSED_INVALID_MANIFEST", f"generated app exited {code}: {rest[-200:]}")
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait(timeout=timeout)
        for stream in (proc.stdin, proc.stdout, proc.stderr):
            if stream is not None:
                stream.close()
    digests = {path: hashlib.sha256((root / path).read_bytes()).hexdigest() for path in FILES}
    return {
        "started": True,
        "name": app["name"],
        "version": app["version"],
        "transport": "subprocess",
        "network": False,
        "readiness": f"READY {app['name']}",
        "shutdown": "STOPPED",
        "exit_code": 0,
        "artifacts": sorted(FILES),
        "digest": hashlib.sha256(archive.canonical(digests)).hexdigest(),
    }


__all__ = ["APP", "DEPLOY", "FILES", "START_TIMEOUT", "TEMPLATE", "TELEMETRY", "build",
           "manifest", "start", "write"]
