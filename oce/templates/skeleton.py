"""Deterministic local application skeleton (B6-I2, section C1.S3).

The generated app is a fixed file set with no clock, no hostname, no random value and no network
dependency. Two builds of the same name are byte-identical, and starting it is an in-process
verification of the generated artifacts, never a socket or a cloud call.
"""
from __future__ import annotations

import hashlib
import json
import pathlib

from . import archive
from .refusals import refuse

TEMPLATE = "oce-app-skeleton"
NAME = "app"

APP = {
    "schema": "oce.template.app.v1",
    "name": NAME,
    "version": "v1",
    "python": "3.12",
    "runtime": "in-process",
    "surfaces": ["api"],
    "cloud": False,
    "telemetry": "local-file",
}

README = """# {name}

A deterministic OCE Book 6 skeleton generated by the B6-I2 template surface.

- Runtime: in-process, standard library only.
- Network: none. The app opens no socket and needs no cloud service.
- Compatibility: version `v1`, inherited from the B6-I1 compatibility window.
- Deploy: local only; publication is not authorized by this stage.

Start it locally with `python -m app` (the generated tests prove the artifact set is complete).
"""

MIGRATION = """-- 0001_init.sql — deterministic initial schema.
CREATE TABLE IF NOT EXISTS items (
    id TEXT PRIMARY KEY,
    created_at TEXT NOT NULL
);
"""

APP_TEST = '''"""Generated smoke test: the artifact set is complete and offline."""
from __future__ import annotations

import json
import pathlib


def test_app_manifest_is_offline() -> None:
    app = json.loads(pathlib.Path("app.json").read_text(encoding="utf-8"))
    assert app["cloud"] is False
    assert app["version"] == "v1"
'''

TELEMETRY = {
    "schema": "oce.template.telemetry.v1",
    "sink": "local-file",
    "network": False,
    "fields": ["event", "status"],
}

DEPLOY = {
    "schema": "oce.template.deploy.v1",
    "target": "local",
    "requires_cloud": False,
    "publication": "NOT_AUTHORIZED",
}

FILES = (
    "README.md",
    "app.json",
    "deploy.json",
    "migrations/0001_init.sql",
    "telemetry.json",
    "tests/test_app.py",
)


def _text(obj) -> str:
    return json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def build(name: str = NAME) -> dict:
    """Return the frozen file set: path -> exact text. Deterministic for a given name."""
    if not isinstance(name, str) or not name or "/" in name or "\\" in name:
        refuse("REFUSED_INVALID_MANIFEST", name)
    app = dict(APP, name=name)
    return {
        "README.md": README.format(name=name),
        "app.json": _text(app),
        "deploy.json": _text(DEPLOY),
        "migrations/0001_init.sql": MIGRATION,
        "telemetry.json": _text(TELEMETRY),
        "tests/test_app.py": APP_TEST,
    }


def manifest(name: str = NAME) -> dict:
    files = build(name)
    entries = [{"path": path, "content": files[path], "mode": "file"}
               for path in sorted(files)]
    return {
        "schema": archive.SCHEMA,
        "template": TEMPLATE,
        "version": archive.VERSION,
        "payload_digest": archive.payload_digest(entries),
        "entries": entries,
    }


def write(dest, name: str = NAME) -> dict:
    """Install the skeleton into an absent or empty directory."""
    return archive.install(manifest(name), dest)


def start(dest) -> dict:
    """Verify a generated app starts locally, in-process, with no cloud or network need."""
    root = pathlib.Path(dest)
    missing = [path for path in FILES if not (root / path).is_file()]
    if missing:
        refuse("REFUSED_INVALID_MANIFEST", f"missing artifacts: {missing}")
    app = json.loads((root / "app.json").read_text(encoding="utf-8"))
    deploy = json.loads((root / "deploy.json").read_text(encoding="utf-8"))
    telemetry = json.loads((root / "telemetry.json").read_text(encoding="utf-8"))
    if app.get("cloud") is not False or deploy.get("requires_cloud") is not False:
        refuse("REFUSED_CLOUD_DEPENDENCY", "app declares a cloud requirement")
    if telemetry.get("network") is not False:
        refuse("REFUSED_NETWORK", "telemetry declares a network sink")
    if deploy.get("publication") != "NOT_AUTHORIZED":
        refuse("REFUSED_INVALID_MANIFEST", "generated app claims publication authority")
    digests = {path: hashlib.sha256((root / path).read_bytes()).hexdigest()
               for path in FILES}
    return {
        "started": True,
        "name": app["name"],
        "version": app["version"],
        "transport": "in-process",
        "network": False,
        "endpoints": [{"service": "api", "address": "local://api", "transport": "in-process"}],
        "artifacts": sorted(FILES),
        "digest": hashlib.sha256(archive.canonical(digests)).hexdigest(),
    }


__all__ = ["APP", "DEPLOY", "FILES", "TEMPLATE", "TELEMETRY", "build", "manifest", "start",
           "write"]
