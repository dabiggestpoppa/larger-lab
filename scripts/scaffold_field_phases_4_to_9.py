def scaffold_module(phase_dir: str, module_name: str) -> None:
    """Create module file, __init__.py entry, and test file."""
    class_name = module_name.title().replace("_", "")

    # Module file
    module_path = os.path.join(phase_dir, f"{module_name}.py")
    module_content = f'''"""{phase_dir.split(os.sep)[-1]}.{module_name}

Field module placeholder. Real implementation pending.

Status: SCAFFOLD - replace this with actual logic.
"""
from pydantic import BaseModel


class {class_name}Config(BaseModel):
    """Configuration for {module_name}."""
    enabled: bool = True


class {class_name}Module:
    """{module_name} field module."""

    def __init__(self):
        self.config = {class_name}Config()
        self.running = False

    def start(self) -> None:
        """Start the module."""
        self.running = True

    def stop(self) -> None:
        """Stop the module."""
        self.running = False
'''
    with open(module_path, "w", encoding="utf-8") as f:
        f.write(module_content)

    # __init__.py
    init_path = os.path.join(phase_dir, "__init__.py")
    init_content = f'''"""{phase_dir.split(os.sep)[-1]} phase modules."""
from .{module_name} import {class_name}Module

__all__ = ["{class_name}Module"]
'''
    with open(init_path, "w", encoding="utf-8") as f:
        f.write(init_content)

    # Test file
    test_path = os.path.join(phase_dir, "tests", f"test_{module_name}.py")
    test_content = f'''"""Test for {module_name}."""
from field.{phase_dir.split(os.sep)[-1]}.{module_name} import {class_name}Module


def test_{module_name}_init():
    """Module initializes with default config."""
    mod = {class_name}Module()
    assert mod.config.enabled is True
    assert mod.running is False


def test_{module_name}_start_stop():
    """Module start/stop toggles running state."""
    mod = {class_name}Module()
    mod.start()
    assert mod.running is True
    mod.stop()
    assert mod.running is False
'''
    with open(test_path, "w", encoding="utf-8") as f:
        f.write(test_content)


def main() -> int:
    """Scaffold all phases and modules. Returns 0 on success."""
    total = 0
    for phase, modules in PHASES.items():
        phase_dir = os.path.join(BASE, phase)
        os.makedirs(os.path.join(phase_dir, "tests"), exist_ok=True)
        for m in modules:
            scaffold_module(phase_dir, m)
            total += 1
        print(f"  [{phase}] {len(modules)} modules")

    # Create conftest.py for pytest
    conftest_path = os.path.join(BASE, "conftest.py")
    with open(conftest_path, "w", encoding="utf-8") as f:
        f.write('"""Pytest config for field/ tests."""\nimport sys\nfrom pathlib import Path\n\nROOT = Path(__file__).parent.parent\nif str(ROOT) not in sys.path:\n    sys.path.insert(0, str(ROOT))\n')

    # Create top-level __init__.py
    top_init = os.path.join(BASE, "__init__.py")
    if not os.path.exists(top_init):
        with open(top_init, "w", encoding="utf-8") as f:
            f.write('"""Field modules - Phases 4-9."""\n')

    print(f"\n✅ Scaffolded {total} modules across {len(PHASES)} phases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
