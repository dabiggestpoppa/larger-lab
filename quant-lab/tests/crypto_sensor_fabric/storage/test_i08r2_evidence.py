def _canonical_payloads(root: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    root.mkdir(parents=True)
    engine = Stack(root).engine("integrity")
    intent_planned = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="integrity",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/integrity.lock"},
    )
    op_id = engine._record_intent(intent_planned, "integrity")
    intent = copy.deepcopy(
        engine.operations.get_phase(
            op_id, rec.RecoveryOperationJournal.PHASE_INTENT
        )
    )
    assert intent is not None
    engine._record_effect(
        op_id,
        intent_planned,
        "integrity",
        detail="canonical effect",
        effect={"kind": "RECORD", "value": 1},
    )
    effect = copy.deepcopy(
        engine.operations.get_phase(
            op_id, rec.RecoveryOperationJournal.PHASE_EFFECT_COMMITTED
        )
    )
    assert effect is not None
    return intent, effect


def _rejected(payload: Any) -> bool:
    try:
        rec.validate_operation_record(payload)
    except rec.RecoveryOperationCorrupt:
        return True
    return False


def build_i08r2_operation_record_integrity_matrix(tmp: Path) -> dict[str, Any]:
    intent, effect = _canonical_payloads(tmp / "canonical")
    mutations: list[tuple[str, Any]] = []

    payload = copy.deepcopy(intent)
