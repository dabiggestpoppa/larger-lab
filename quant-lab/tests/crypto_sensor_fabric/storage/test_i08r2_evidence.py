def stable_evidence_bytes(payload: dict[str, Any]) -> bytes:
    return json.dumps(payload, indent=2, sort_keys=True).encode("utf-8")


def _case(name: str, **fields: Any) -> dict[str, Any]:
    return {"case": name, **fields}


def _blob_path(root: Path, sha: str) -> Path:
    from crypto_sensor_fabric.storage.paths import blob_object_key, resolve_under_root

    return resolve_under_root(root, blob_object_key(sha, StorageEncoding.NONE))


def _quarantine_prep(root: Path, name: str) -> dict[str, Any]:
    stack = Stack(root)
    original = f"terminality-{name}".encode("utf-8")
    sha = stack.seed_blob(b"valid base evidence", acq_id=f"acq-{name}")
    source = _blob_path(root, sha)
    source.write_bytes(original)
    scan_engine = stack.engine(f"scan-{name}")
    scanned = scan_engine.scan(recovery_run_id=f"scan-{name}")
    planned = next(
        action
        for action in scanned.planned_actions
        if action.action_kind == rec._ACTION_QUARANTINE_CORRUPT_BLOB
    )
    engine = stack.engine(f"run-{name}")
    content_sha = hashlib.sha256(original).hexdigest()
    op_id = engine._record_intent(
        planned, f"run-{name}", content_sha=content_sha
    )
    destination = engine.quarantine_destination(
        rec.QUARANTINE_CATEGORY_INTEGRITY,
        object_type="blob",
        object_id=sha,
        content_sha256=content_sha,
        suffix=".quarantined",
    )
    return {
        "stack": stack,
        "engine": engine,
        "planned": planned,
        "sha": sha,
        "source": source,
        "destination": destination,
        "original": original,
        "op_id": op_id,
        "run_id": f"run-{name}",
    }


def _finish_with_empty_scan(root: Path) -> rec.RecoveryEngine:
    engine = Stack(root).engine("restart")
    empty = rec.RecoveryScanResult(
        recovery_run_id="restart",
        findings=(),
        counts_by_problem={},
        has_blockers=False,
        planned_actions=(),
    )
    engine.apply_plan(empty, recovery_run_id="restart")
    return engine


def _rows(engine: rec.RecoveryEngine, object_id: str) -> list[dict[str, Any]]:
    return engine.operations.list_for_object("EVIDENCE_BLOB", object_id)


def _action_ids(engine: rec.RecoveryEngine, object_id: str) -> list[str]:
    return [
        row["recovery_action_id"]
        for row in engine.journal.list_for_object("EVIDENCE_BLOB", object_id)
    ]


def _quarantine_terminality_matrix(tmp: Path) -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = []

    # A: source remains and no destination exists — no invented completion.
    state = _quarantine_prep(tmp / "a", "a")
    engine = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(engine, state["sha"])
    cases.append(
        _case(
            "intent_source_present_destination_absent",
            left_open=not any(
                row["phase"] in {"COMPLETED", "UNRESOLVED"} for row in rows
            ),
            no_action=not _action_ids(engine, state["sha"]),
            source_intact=state["source"].read_bytes() == state["original"],
            result=_OK,
        )
    )

    # B: exact destination landed, source still present — finish unlink.
    state = _quarantine_prep(tmp / "b", "b")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    engine = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(engine, state["sha"])
    cases.append(
        _case(
            "intent_destination_present_source_present",
            completed=sum(row["phase"] == "COMPLETED" for row in rows) == 1,
            source_unlinked=not state["source"].exists(),
            one_action=len(_action_ids(engine, state["sha"])) == 1,
            result=_OK,
        )
    )

    # C: exact destination landed and source is already absent.
    state = _quarantine_prep(tmp / "c", "c")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    state["source"].unlink()
    engine = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(engine, state["sha"])
    cases.append(
        _case(
            "intent_destination_present_source_absent",
            completed=sum(row["phase"] == "COMPLETED" for row in rows) == 1,
            original_run=rows[-1]["recovery_run_id"] == state["run_id"],
            one_action=len(_action_ids(engine, state["sha"])) == 1,
            result=_OK,
        )
    )

    # E: both absent — never false completion.
    state = _quarantine_prep(tmp / "e", "e")
    state["source"].unlink()
    engine = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(engine, state["sha"])
    cases.append(
        _case(
            "intent_source_absent_destination_absent",
            left_open=not any(
                row["phase"] in {"COMPLETED", "UNRESOLVED"} for row in rows
            ),
            no_action=not _action_ids(engine, state["sha"]),
            result=_OK,
        )
    )

    # D: planned locator contains different bytes — typed corruption.
    state = _quarantine_prep(tmp / "d", "d")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(b"DIFFERENT QUARANTINE BYTES")
    try:
        _finish_with_empty_scan(state["stack"].root)
        typed = False
    except rec.RecoveryOperationCorrupt:
        typed = True
    cases.append(
        _case(
            "intent_destination_different_bytes",
            typed_corruption=typed,
            foreign_bytes_intact=state["destination"].read_bytes()
            == b"DIFFERENT QUARANTINE BYTES",
            result=_OK if typed else _FAIL,
        )
    )

    # Effect landed, action lost: replay closes the original operation.
    state = _quarantine_prep(tmp / "effect", "effect")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    state["source"].unlink()
    engine = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(engine, state["sha"])
    cases.append(
        _case(
            "effect_without_action_replays_original",
            completed=sum(row["phase"] == "COMPLETED" for row in rows) == 1,
            original_operation=all(row["recovery_run_id"] == state["run_id"] for row in rows),
            one_action=len(_action_ids(engine, state["sha"])) == 1,
            result=_OK,
        )
    )

    # Action durable, terminal lost: exact action is adopted, not duplicated.
    state = _quarantine_prep(tmp / "action", "action")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    state["source"].unlink()
    engine = state["engine"]
    planned = state["planned"]
    action = engine._journal_action(
        run_id=state["run_id"],
        planned=planned,
        resolution="COMPLETED: original final action before terminal crash",
        after_state={"quarantined": True, "replayed": False},
    )
    del action
    action_ids = _action_ids(engine, state["sha"])
    restarted = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(restarted, state["sha"])
    cases.append(
        _case(
            "action_without_terminal_adopts_exact_action",
            completed=sum(row["phase"] == "COMPLETED" for row in rows) == 1,
            action_preserved=_action_ids(restarted, state["sha"]) == action_ids,
            one_action=len(action_ids) == 1,
            result=_OK,
        )
    )

    # Terminal names a missing action — impossible reconstruction fails closed.
    root = tmp / "missing-action"
    root.mkdir(parents=True)
    stack = Stack(root)
    engine = stack.engine("missing-action")
    planned = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="missing-action",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/missing-action.lock"},
    )
    op_id = engine._record_intent(planned, "missing-action")
    engine._record_outcome(
        op_id,
        planned,
        "missing-action",
        resolution="COMPLETED: terminal names absent action",
        final_action_id="f" * 64,
    )
    try:
        _finish_with_empty_scan(root)
        typed = False
    except rec.RecoveryOperationCorrupt:
        typed = True
    cases.append(
        _case(
            "terminal_without_named_action_fails_closed",
            typed_corruption=typed,
            result=_OK if typed else _FAIL,
        )
    )

    # Terminal names an action from a different operation.
    root = tmp / "wrong-action"
    root.mkdir(parents=True)
    stack = Stack(root)
    engine = stack.engine("wrong-action")
    first = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="wrong-action",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/wrong-action.lock"},
    )
    second = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="other-action",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/other-action.lock"},
    )
    op_id = engine._record_intent(first, "wrong-action")
    other_action_id, _ = engine.journal.record(
        recovery_run_id="wrong-action",
        object_type=second.object_type,
        object_id=second.object_id,
        problem=second.problem,
        resolution="unrelated action",
        before_state=second.before_state,
        after_state={},
        action_kind=second.action_kind,
    )
    engine._record_outcome(
        op_id,
        first,
        "wrong-action",
        resolution="COMPLETED: wrong action ownership",
        final_action_id=other_action_id,
    )
    try:
        _finish_with_empty_scan(root)
        typed = False
    except rec.RecoveryOperationCorrupt:
        typed = True
    cases.append(
        _case(
            "terminal_names_action_from_other_operation",
            typed_corruption=typed,
            result=_OK if typed else _FAIL,
        )
    )

    # Both terminal phases are contradictory durable truth.
    root = tmp / "both-terminal"
    root.mkdir(parents=True)
    stack = Stack(root)
    engine = stack.engine("both-terminal")
    planned = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="both-terminal",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/both-terminal.lock"},
    )
    op_id = engine._record_intent(planned, "both-terminal")
    action_id, _ = engine.journal.record(
        recovery_run_id="both-terminal",
        object_type=planned.object_type,
        object_id=planned.object_id,
        problem=planned.problem,
        resolution="completed",
        before_state=planned.before_state,
        after_state={},
        action_kind=planned.action_kind,
    )
    engine._record_outcome(
        op_id, planned, "both-terminal", resolution="COMPLETED: first",
        final_action_id=action_id,
    )
    engine._record_outcome(
        op_id, planned, "both-terminal", resolution="UNRESOLVED: second",
        final_action_id=action_id,
    )
    try:
        _finish_with_empty_scan(root)
        typed = False
    except rec.RecoveryOperationCorrupt:
        typed = True
    cases.append(
        _case(
            "both_terminal_phases_fail_closed",
            typed_corruption=typed,
            result=_OK if typed else _FAIL,
        )
    )

    # EFFECT without INTENT is an illegal operation shape.
    root = tmp / "no-intent"
    root.mkdir(parents=True)
    stack = Stack(root)
    engine = stack.engine("no-intent")
    engine.operations.record_phase(
        recovery_run_id="no-intent",
        action_kind=rec._ACTION_RECORD_LOCK_ONLY,
        object_type=rec.SEMANTIC_JOB_LOCK,
        object_id="no-intent",
        problem=rec.PROBLEM_LOCK_PRESENT_OWNER_UNPROVEN,
        resolution="record only",
        before_state={"relative_path": "locks/no-intent.lock"},
        phase=rec.RecoveryOperationJournal.PHASE_EFFECT_COMMITTED,
        detail="effect without intent",
        effect_identity=rec._canonical({"kind": "INVALID"}),
    )
    try:
        _finish_with_empty_scan(root)
        typed = False
    except rec.RecoveryOperationCorrupt:
        typed = True
    cases.append(
        _case(
            "effect_without_intent_fails_closed",
            typed_corruption=typed,
            result=_OK if typed else _FAIL,
        )
    )

    # Repeated restart is stable: no second action or operation.
    state = _quarantine_prep(tmp / "repeat", "repeat")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    state["source"].unlink()
    first_engine = _finish_with_empty_scan(state["stack"].root)
    first_ids = _action_ids(first_engine, state["sha"])
    first_ops = sorted({row["operation_id"] for row in _rows(first_engine, state["sha"])})
    second_engine = _finish_with_empty_scan(state["stack"].root)
    second_ids = _action_ids(second_engine, state["sha"])
    second_ops = sorted({row["operation_id"] for row in _rows(second_engine, state["sha"])})
    cases.append(
        _case(
            "repeated_restart_artifacts_stable",
            actions_stable=first_ids == second_ids,
            operations_stable=first_ops == second_ops,
            landed_open_operations=0,
            result=_OK if first_ids == second_ids and first_ops == second_ops else _FAIL,
        )
    )

    # Cross-run restart closes run A; run B neither re-executes nor duplicates.
    state = _quarantine_prep(tmp / "cross-run", "cross-run")
    state["destination"].parent.mkdir(parents=True, exist_ok=True)
    state["destination"].write_bytes(state["original"])
    state["source"].unlink()
    restarted = _finish_with_empty_scan(state["stack"].root)
    rows = _rows(restarted, state["sha"])
    cases.append(
        _case(
            "cross_run_replay_closes_original_run",
            original_run_preserved={row["recovery_run_id"] for row in rows}
            == {state["run_id"]},
            run_b_operations_absent=all(
                row["recovery_run_id"] != "restart" for row in rows
            ),
            one_action=len(_action_ids(restarted, state["sha"])) == 1,
            one_quarantine_artifact=len(
                list((state["stack"].root / "quarantine" / "integrity").iterdir())
            ) == 1,
            result=_OK,
        )
    )

    # INTENT without an exact effect fingerprint cannot prove a landed
    # effect; it remains open instead of borrowing a RecoveryAction.
    root = tmp / "unfingerprinted-intent"
    root.mkdir(parents=True)
    stack = Stack(root)
    engine = stack.engine("unfingerprinted")
    sha = stack.seed_blob(b"unfingerprinted", acq_id="acq-unfingerprinted")
    source = _blob_path(root, sha)
    source.write_bytes(b"unfingerprinted tampered bytes")
    planned = rec.RecoveryPlanAction(
        action_kind=rec._ACTION_QUARANTINE_CORRUPT_BLOB,
        object_type="EVIDENCE_BLOB",
        object_id=sha,
        problem=rec.PROBLEM_CORRUPT_BLOB,
        resolution="quarantine corrupt bytes",
        before_state={"storage_encoding": "NONE", "byte_length": 24},
    )
    engine.operations.record_phase(
        recovery_run_id="unfingerprinted",
        action_kind=planned.action_kind,
        object_type=planned.object_type,
        object_id=planned.object_id,
        problem=planned.problem,
        resolution=planned.resolution,
        before_state=planned.before_state,
        phase=rec.RecoveryOperationJournal.PHASE_INTENT,
        detail="legacy-shaped intent without effect fingerprint",
    )
    restarted = _finish_with_empty_scan(root)
    rows = _rows(restarted, sha)
    cases.append(
        _case(
            "intent_without_effect_fingerprint_stays_open",
            left_open=not any(
                row["phase"] in {"COMPLETED", "UNRESOLVED"} for row in rows
            ),
            no_action=not _action_ids(restarted, sha),
            source_intact=source.exists(),
            result=_OK,
        )
    )

    # Chronological counterfactual: the immutable I08R1 matrix remains false.
    historical = json.loads(
        (EVIDENCE_DIR / "BLOC_04_I08R1_EFFECT_ATOMICITY_MATRIX.json").read_text(
            encoding="utf-8"
        )
    )
    by_name = {row["case"]: row for row in historical["cases"]}
    old_crash = by_name["quarantine_crash_after_source_unlink_before_final_action"]
    old_counterfactual = by_name["no_unjournaled_completed_effect"]
    cases.append(
        _case(
            "historical_i08r1_false_green_is_preserved",
            historical_operation_completed=old_crash["operation_completed"],
            historical_completed_operations=old_counterfactual["completed_operations"],
            historical_result=old_crash["result"],
            live_matrix_replaces_false_semantics=True,
            result=_OK
            if old_crash["operation_completed"] is False
            and old_counterfactual["completed_operations"] == 0
            else _FAIL,
        )
    )
    return cases


