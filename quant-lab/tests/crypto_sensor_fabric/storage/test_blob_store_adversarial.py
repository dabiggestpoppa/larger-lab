def deterministic_bytes(size: int, seed: int = 12345) -> bytes:
    out = bytearray()
    state = seed
    while len(out) < size:
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(state & 0xFF)
    return bytes(out)


def make_store(tmp_path: Path, **kwargs: object) -> LocalBlobStore:
    return LocalBlobStore(tmp_path, clock=lambda: FIXED, **kwargs)


def final_path_for(tmp_path: Path, sha: str, encoding: StorageEncoding) -> Path:
    suffix = ".blob" if encoding is StorageEncoding.NONE else ".blob.zst"
    return (
        tmp_path / "blobs" / "sha256" / sha[:2] / sha[2:4] / f"{sha}{suffix}"
    )


class TestStagingIsolation:
    @pytest.mark.parametrize(
        "point",
        [
            FaultPoint.STAGE_WRITE,
            FaultPoint.BEFORE_FILE_FSYNC,
            FaultPoint.BEFORE_STAGE_VERIFY,
            FaultPoint.BEFORE_PUBLISH,
        ],
    )
    def test_partial_stage_never_exposes_final(self, tmp_path, point: FaultPoint) -> None:
        data = b"crash during staging"
        store = make_store(tmp_path)
        sha = hashlib.sha256(data).hexdigest()
        hooks = RaiseFaultHook(point)
        with pytest.raises(FaultError):
            store.put(
                io.BytesIO(data),
                storage_encoding=StorageEncoding.NONE,
                source_media_type=MEDIA,
                fault_hooks=hooks,
            )
        assert not final_path_for(tmp_path, sha, StorageEncoding.NONE).exists()
        assert list((tmp_path / "staging").rglob("*.partial")), "partial staging may exist"

    def test_adversarial_reader_never_observes_partial_final(self, tmp_path) -> None:
        data = deterministic_bytes(2_000_000, seed=99)
        sha = hashlib.sha256(data).hexdigest()
        final = final_path_for(tmp_path, sha, StorageEncoding.NONE)
        store = make_store(tmp_path, chunk_size=1 << 14)
        errors: list[str] = []

        def writer() -> None:
            try:
                store.put(
                    io.BytesIO(data),
                    storage_encoding=StorageEncoding.NONE,
                    source_media_type=MEDIA,
                )
            except Exception as exc:  # noqa: BLE001 - test harness only
                errors.append(repr(exc))

        thread = threading.Thread(target=writer)
        thread.start()
        observed = 0
        while thread.is_alive() or observed == 0:
            if final.exists():
                observed += 1
                with open(final, "rb") as fh:
                    got = fh.read()
                assert got == data, "reader observed a partial final object!"
            time.sleep(0.001)
        thread.join()
        assert not errors
        assert observed >= 1


class TestCrashMatrix:
    """I03 §74: deterministic fault injection, one row per crash point."""

    EXPECTED_STATES: ClassVar[dict[FaultPoint, str]] = {
        FaultPoint.STAGE_WRITE: "UNCOMMITTED_STAGING",
        FaultPoint.BEFORE_FILE_FSYNC: "UNCOMMITTED_STAGING",
        FaultPoint.BEFORE_STAGE_VERIFY: "UNCOMMITTED_STAGING",
        FaultPoint.BEFORE_PUBLISH: "UNCOMMITTED_STAGING",
        FaultPoint.AFTER_PUBLISH_BEFORE_DIR_FSYNC: "ORPHAN_DURABLE_BLOB",
        FaultPoint.AFTER_DIR_FSYNC_BEFORE_RETURN: "DURABLE_COMMITTED",
    }

    @pytest.mark.parametrize("point", list(EXPECTED_STATES))
    def test_crash_row(self, tmp_path, point: FaultPoint) -> None:
        data = f"crash-{point.value}".encode()
        store = make_store(tmp_path)
        sha = hashlib.sha256(data).hexdigest()
        hooks = RaiseFaultHook(point)
        ops = ListOpRecorder()
        try:
            store.put(
                io.BytesIO(data),
                storage_encoding=StorageEncoding.NONE,
                source_media_type=MEDIA,
                fault_hooks=hooks,
                ops=ops,
            )
            raised = False
        except FaultError:
            raised = True
        assert raised

        final_exists = final_path_for(tmp_path, sha, StorageEncoding.NONE).exists()
        staging_exists = bool(list((tmp_path / "staging").rglob("*.partial")))
        success_returned = OP_SUCCESS_RETURN in ops.ops
        state = self.EXPECTED_STATES[point]

        if state == "UNCOMMITTED_STAGING":
            assert final_exists is False
            assert success_returned is False
        elif state == "ORPHAN_DURABLE_BLOB":
            assert final_exists is True
            assert success_returned is False
            assert OP_PARENT_DIR_FSYNC not in ops.ops
        elif state == "DURABLE_COMMITTED":
            assert final_exists is True
            assert success_returned is False  # crash before return, but durable
            assert OP_PARENT_DIR_FSYNC in ops.ops
            check = store.verify_blob(sha, StorageEncoding.NONE)
            assert check.integrity_state is IntegrityState.LOCAL_HASH_VERIFIED
        assert staging_exists is True

    def test_crash_matrix_artifact_written(self, tmp_path) -> None:
        """Regenerate BLOC_04_I03_CRASH_MATRIX.json deterministically (I03 §74)."""
        rows: list[dict[str, object]] = []
        for point, expected_state in self.EXPECTED_STATES.items():
            data = f"crash-matrix-{point.value}".encode()
            store = make_store(tmp_path)
            sha = hashlib.sha256(data).hexdigest()
            ops = ListOpRecorder()
            with pytest.raises(FaultError):
                store.put(
                    io.BytesIO(data),
                    storage_encoding=StorageEncoding.NONE,
                    source_media_type=MEDIA,
                    fault_hooks=RaiseFaultHook(point),
                    ops=ops,
                )
            rows.append(
                {
                    "fault_point": point.value,
                    "final_exists": final_path_for(
                        tmp_path, sha, StorageEncoding.NONE
                    ).exists(),
                    "staging_exists": bool(
                        list((tmp_path / "staging").rglob("*.partial"))
                    ),
                    "success_returned": OP_SUCCESS_RETURN in ops.ops,
                    "expected_state": expected_state,
                    "test_name": f"test_crash_row[{point.value}]",
                }
            )
            # row-local staging state: clear this row's leftover before the next
            for leftover in (tmp_path / "staging").rglob("*.partial"):
                leftover.unlink()
        out_path = EVIDENCE_DIR / "BLOC_04_I03_CRASH_MATRIX.json"
        out_path.write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
        assert len(rows) == 6
        assert all(row["success_returned"] is False for row in rows)

    def test_retry_after_durable_publication_dedupes(self, tmp_path) -> None:
        data = b"retry after crash F"
        store = make_store(tmp_path)
        hooks = RaiseFaultHook(FaultPoint.AFTER_DIR_FSYNC_BEFORE_RETURN)
        with pytest.raises(FaultError):
            store.put(
                io.BytesIO(data),
                storage_encoding=StorageEncoding.NONE,
                source_media_type=MEDIA,
                fault_hooks=hooks,
            )
        result = store.put_bytes(data, storage_encoding=StorageEncoding.NONE, source_media_type=MEDIA)
        assert result.disposition is PutDisposition.REUSED_EXISTING


