class TestConcurrency:
    def test_concurrent_identical_writers_one_final(self, tmp_path) -> None:
        data = deterministic_bytes(400_000, seed=20260904)
        store = make_store(tmp_path, chunk_size=1 << 16)
        count = 8
        results: list[str] = []
        lock = threading.Lock()
        barrier = threading.Barrier(count)

        def worker() -> None:
            barrier.wait()
            result = store.put(
                io.BytesIO(data),
                storage_encoding=StorageEncoding.ZSTD,
                source_media_type=MEDIA,
            )
            with lock:
                results.append(result.disposition.value)

        threads = [threading.Thread(target=worker) for _ in range(count)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()

        assert results.count(PutDisposition.COMMITTED_NEW.value) == 1
        assert results.count(PutDisposition.REUSED_EXISTING.value) == count - 1
        sha = hashlib.sha256(data).hexdigest()
        finals = list((tmp_path / "blobs" / "sha256" / sha[:2] / sha[2:4]).glob("*.blob.zst"))
        assert len(finals) == 1
        check = store.verify_blob(sha, StorageEncoding.ZSTD, expected_byte_length=len(data))
        assert check.integrity_state is IntegrityState.LOCAL_HASH_VERIFIED

    def test_concurrent_distinct_writers_no_crosstalk(self, tmp_path) -> None:
        store = make_store(tmp_path)
        payloads = [deterministic_bytes(50_000, seed=i) for i in range(6)]
        results: list[str] = []
        lock = threading.Lock()
        barrier = threading.Barrier(len(payloads))

        def worker(data: bytes) -> None:
            barrier.wait()
            result = store.put(
                io.BytesIO(data),
                storage_encoding=StorageEncoding.NONE,
                source_media_type=MEDIA,
            )
            with lock:
                results.append(result.blob.blob_sha256)

        threads = [threading.Thread(target=worker, args=(p,)) for p in payloads]
        for t in threads:
            t.start()
        for t in threads:
            t.join()

        assert sorted(results) == sorted(hashlib.sha256(p).hexdigest() for p in payloads)
        for p in payloads:
            sha = hashlib.sha256(p).hexdigest()
            with store.open_blob(sha, StorageEncoding.NONE) as fh:
                assert fh.read() == p


